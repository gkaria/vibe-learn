#!/bin/bash
# briefing-demo.sh [--screenshots] [DIR] — build the README's `my-api` demo
# project and render its session briefing. --screenshots also rewrites
# docs/briefing-{index,session,health}.png with headless Chrome.
#
# DIR defaults to $TMPDIR/vibe-learn-demo/my-api. A prior generated demo can
# be recreated; an existing directory without the demo marker is left alone.
# The session continues the JWT auth example used throughout the README; the
# health history is tests/fixtures/health-sample.sh (the mockup's data). HOME
# points inside DIR so nothing is read from or written to your real
# ~/.vibe-learn.

set -euo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
SCREENSHOTS=false
if [ "${1:-}" = "--screenshots" ]; then SCREENSHOTS=true; shift; fi
PROJECT="${1:-${TMPDIR:-/tmp}/vibe-learn-demo/my-api}"
PROJECT="${PROJECT%/}"
case "$(basename "$PROJECT")" in my-api) ;; *) echo "DIR must end in /my-api" >&2; exit 1 ;; esac

if [ -e "$PROJECT" ] || [ -L "$PROJECT" ]; then
  if [ -L "$PROJECT" ] || [ ! -f "$PROJECT/.vibe-learn-demo" ]; then
    echo "Refusing to replace an existing non-demo directory: $PROJECT" >&2
    exit 1
  fi
  rm -rf "$PROJECT"
fi
mkdir -p "$PROJECT/src/routes" "$PROJECT/src/middleware" "$PROJECT/.vibe-learn" "$PROJECT/.home"
printf 'Generated by docs/demo/briefing-demo.sh\n' > "$PROJECT/.vibe-learn-demo"
export HOME="$PROJECT/.home"
cd "$PROJECT"

git init -q
git config user.email demo@example.com
git config user.name demo
cat > src/routes/user.ts <<'EOF'
import { Router } from "express";

const router = Router();

router.get("/profile", (req, res) => res.json({ id: 1 }));
router.get("/settings", (req, res) => res.json({ theme: "dark" }));

export default router;
EOF
echo '{"name":"my-api","dependencies":{"express":"^4.19.2"}}' > package.json
git add -A && git commit -qm "initial routes"

cat > src/middleware/auth.ts <<'EOF'
import type { Request, Response, NextFunction } from "express";
import jwt from "jsonwebtoken";

const secret = process.env.JWT_SECRET ?? "";

// Fail closed: every path that doesn't verify a token returns 401.
export function requireAuth(req: Request, res: Response, next: NextFunction) {
  const header = req.headers.authorization ?? "";
  const token = header.startsWith("Bearer ") ? header.slice(7) : "";
  if (!token || !secret) return res.status(401).json({ error: "unauthorized" });

  try {
    const payload = jwt.verify(token, secret);
    (req as Request & { user?: unknown }).user = payload;
    return next();
  } catch {
    return res.status(401).json({ error: "invalid token" });
  }
}
EOF
cat > src/routes/user.ts <<'EOF'
import { Router } from "express";
import { requireAuth } from "../middleware/auth";

const router = Router();
router.use(requireAuth);

router.get("/profile", (req, res) => res.json({ id: 1 }));
router.get("/settings", (req, res) => res.json({ theme: "dark" }));

export default router;
EOF
echo '{"name":"my-api","dependencies":{"express":"^4.19.2","jsonwebtoken":"^9.0.2"}}' > package.json

