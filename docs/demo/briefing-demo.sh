  session_id: "demo-jwt-auth", started_at: $t, event_count: 17, current_turn: 4,
  harness: "claude-code", harness_version: "2.5.0", model: "claude-opus-5.5", effort: "high",
  transcript_path: $tp, git_head: null, git_dirty: true}' > .vibe-learn/session-meta.json

