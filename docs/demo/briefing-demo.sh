BRIEFING="$PROJECT/.vibe-learn/briefing"
echo "$BRIEFING"
$SCREENSHOTS || exit 0

CHROME="${CHROME:-/Applications/Google Chrome.app/Contents/MacOS/Google Chrome}"
[ -x "$CHROME" ] || CHROME="$(command -v google-chrome || command -v chromium || true)"
[ -x "$CHROME" ] || { echo "Chrome not found; set CHROME=/path/to/chrome" >&2; exit 1; }

# shot PAGE OUT HEIGHT — 1280 CSS px wide at 2x. Headless Chrome can linger
# after writing the file, so wait for the file and then stop it.
shot() {
  local out="$REPO/docs/$2" profile pid tmp_dir tmp_out
  profile="$(mktemp -d)"
  tmp_dir="$(mktemp -d)"
  tmp_out="$tmp_dir/$2"
  "$CHROME" --headless=new --disable-gpu --hide-scrollbars --force-device-scale-factor=2 \
    --window-size="1280,$3" --user-data-dir="$profile" --screenshot="$tmp_out" \
    "file://$BRIEFING/$1" >/dev/null 2>&1 &
  pid=$!
  for _ in $(seq 1 60); do
    [ -s "$tmp_out" ] && break
    kill -0 "$pid" 2>/dev/null || break
    sleep 0.5
  done
  [ -s "$tmp_out" ] && sleep 0.5
  kill "$pid" 2>/dev/null || true
  wait "$pid" 2>/dev/null || true
  rm -rf "$profile"
  if [ ! -s "$tmp_out" ]; then
    rm -rf "$tmp_dir"
    echo "Screenshot failed for $1; kept $out" >&2
    return 1
  fi
  mv "$tmp_out" "$out"
  rm -rf "$tmp_dir"
  echo "$out"
}
session="$(cd "$BRIEFING" && ls sessions/*.html | head -1)"
shot index.html briefing-index.png 720
shot "$session" briefing-session.png 960
shot health.html briefing-health.png 1380
