# A Claude Code transcript with only the tool calls usage.sh counts.
tool() {
  local input="${2:-}"
  jq -cn --arg t "$(ts 14:10)" --arg n "$1" --argjson i "${input:-null}" \
    '{type:"assistant",timestamp:$t,message:{content:[{type:"tool_use",name:$n,input:($i // {})}]}}'
}
{
  for _ in 1 2 3 4 5 6 7 8 9; do tool Read; done
  for _ in 1 2 3 4 5 6 7; do tool Grep; done
  for _ in 1 2 3 4 5 6 7; do tool Bash; done
  for _ in 1 2 3 4 5 6; do tool Edit; done
  tool Write; tool Write
  tool Skill '{"skill":"explain"}'
} > .home/transcript.jsonl

